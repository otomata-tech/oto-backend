"""What oto 1 derives from a connector's DESCRIPTION, when it serves it by the generic reader (`tools/decrits.py`).

Decided on 05/11/2026 (step 2 of the convergence rule, connectors repo `docs/conception/fabrique.md`): a connector
described in the library is served by ONE reader written once, not by a hand-written tool file; since 09/11/2026 the
reader runs the description by the library's engine (`oto.connectors.engine`), no client of its own. Only the
connectors explicitly INSCRIBED are served: a registry entry built by `providers._model._decrit` (it carries
`decrit`). No hand-written connector moves to it.

This module is PURE (no I/O, no `oto_mcp` import at module level): from a served description
(`oto.connectors.descriptions.load`, generated by the fabrique) it derives

- the PAIR of tools: `<ns>` serves the functions `act: false` (`LECTURE`, or `SIMULATION` when one of them writes, a
  draft), `<ns>_act` the functions `act: true` (`ACTE`); the `op` of a call is the function's name;
  the description's `exposure` block is IGNORED (gap): always this pair, whatever its mode. The exposure modes
  and the grouping by family are decided in oto-core, `docs/conception/exposition-des-fonctions.md`;
- the EFFECT of each op (`tools/effets.py`'s classes): `read` → `lire`; `write` that does not commit (`act: false`) →
  `ecrire`; `write` that commits → `envoyer`; `sensitive` → its declared `effect`, `send` → `envoyer`, `destroy` →
  `detruire`. A sensitive function without `effect` is refused at mount: confirming it says nothing of what it does;
- the BATCHES: every list argument of an op that writes or sends, bounded by the smallest `maxItems` and by `LOT_MAX`
  (an op that writes without a list of its own takes the tool's first batch, as `LOTS` asks);
- the PERSONAL arguments (`personal: true`, at any depth), that the call log never writes in clear;
- the CREDENTIAL: one secret of the account, a key (`api_key`, `bearer`) kept in the vault under `key`, or a service
  account's JSON key file (`oauth2_jwt_bearer`) kept under the description's field name; or a login and a password
  (`basic`), kept as two fields under the description's names (since 11/11/2026);
- the PLATFORM key (mode `platform`, since 11/11/2026): resolved by the cascade like any shared key (grants, quota),
  each call noting the quantity its declared cost settles (`tools/decrits.py`); the probe function, which reads the
  account itself, is not served on it;
- the ACCESS LEVELS (`auth.access_levels`, since 13/11/2026): the declaration `connectors.access_levels` reads like a
  hand-written connector's `ACCESS_LEVELS`, its default level included (`auth.default_level`);
- what the reader CANNOT serve, refused at mount, never approximated.
"""
from __future__ import annotations

from functools import lru_cache
from typing import Optional

#: The arguments that pagination adds to a served input: the engine reads them, the vendor never receives them.
ARGUMENTS_DE_PAGINATION = ("all_pages", "max_pages")
_PAR_EFFET = {"send": "envoyer", "destroy": "detruire"}
#: The kinds of `auth` whose one secret is a key, kept in the vault under `CHAMP_DE_CLE` (`access.resolve_api_key`).
_AUTH_A_CLE = ("api_key", "bearer")
#: The kind of `auth` whose one secret is a service account's JSON key file, kept under the description's field name
#: (`access.resolve_credential_fields`), as `google_analytics` keeps its own.
_AUTH_A_COMPTE_DE_SERVICE = "oauth2_jwt_bearer"
#: The kind of `auth` of a login and a password: two fields of the account, kept under the description's names
#: (`access.resolve_credential`), the login not secret, the password secret.
_AUTH_BASIQUE = "basic"
#: The key field of a served connector's credential in the vault, for a key (`_AUTH_A_CLE`).
CHAMP_DE_CLE = "key"


class DescriptionNonServie(ValueError):
    """A description the reader does not know how to serve: refused at mount, with every reason."""


def charger(nom: str) -> dict:
    """The served description of `nom`, from the library (never a YAML file)."""
    from oto.connectors import descriptions as servies
    return servies.load(nom)


def inscrits() -> tuple:
    """The registry entries served by the reader: those built by `_decrit` (they carry `decrit`)."""
    from .. import providers
    return tuple(c for c in providers.REGISTRY.values() if c.decrit)


# --- the pair and the effects --------------------------------------------------------------------------------------

def agit(fonction: dict) -> bool:
    """`act` declared, otherwise from the class (`read` → false, `write` and `sensitive` → true)."""
    return fonction.get("act", fonction["class"] != "read")


def classe(fonction: dict) -> str:
    """`lire`, `ecrire`, `envoyer` or `detruire` — what one call of the function does."""
    sorte = fonction["class"]
    if sorte == "read":
        return "lire"
    if sorte == "write":
        return "envoyer" if agit(fonction) else "ecrire"
    effet = fonction.get("effect")
    if effet not in _PAR_EFFET:
        raise DescriptionNonServie(f"function {fonction['name']}: sensitive without `effect` (send or destroy)")
    return _PAR_EFFET[effet]


def espace(description: dict) -> str:
    return description["connector"]["namespace"]


def outils(description: dict) -> dict[str, list[dict]]:
    """`{tool: its functions}`: `<ns>` (act false) and `<ns>_act` (act true), each only when it has a function."""
    ns = espace(description)
    paire = {ns: [f for f in description["functions"] if not agit(f)],
             f"{ns}_act": [f for f in description["functions"] if agit(f)]}
    return {outil: fonctions for outil, fonctions in paire.items() if fonctions}


def lecteur_simule(fonctions: list[dict]) -> bool:
    """The `<ns>` side prepares something (a draft: `write` with `act: false`): `SIMULATION`, not `LECTURE`."""
    return any(f["class"] != "read" for f in fonctions)


def effets(description: dict) -> dict[str, dict[str, str]]:
    """`tools/effets.EFFETS` lines of the served tools: `{tool: {class: "op op …"}}`, for every tool that is not
    `LECTURE` (a `LECTURE` tool is declared by its annotation)."""
    out: dict[str, dict[str, str]] = {}
    for outil, fonctions in outils(description).items():
        if outil == espace(description) and not lecteur_simule(fonctions):
            continue
        par_classe: dict[str, list[str]] = {}
        for f in fonctions:
            par_classe.setdefault(classe(f), []).append(f["name"])
        out[outil] = {c: " ".join(ops) for c, ops in par_classe.items()}
    return out


# --- batches and lists ---------------------------------------------------------------------------------------------

def _listes(fonction: dict) -> list[str]:
    """The top-level list arguments of the function, in the order of its input."""
    out = []
    for nom, schema in fonction["input"]["properties"].items():
        types = schema.get("type")
        if types == "array" or (isinstance(types, list) and "array" in types):
            out.append(nom)
    return out


def lots(description: dict, plafond: int) -> dict[str, tuple[str, int, tuple[str, ...]]]:
    """`{"tool:op": (key, max, other keys)}`: every op that writes or sends with list arguments carries them as ONE
    batch, at most the smallest `maxItems` they declare, and at most `plafond`. An op that writes or sends WITHOUT a
    list of its own, on a tool where another op carries one, takes the tool's first batch: the rule of
    `tools/effets.LOTS` (every op that writes on a tool with a list argument declares its batch)."""
    out = {}
    for outil, fonctions in outils(description).items():
        ecrivent = [f for f in fonctions if classe(f) in ("ecrire", "envoyer")]
        propres = {}
        for f in ecrivent:
            listes = _listes(f)
            if not listes:
                continue
            bornes = [f["input"]["properties"][n]["maxItems"] for n in listes
                      if "maxItems" in f["input"]["properties"][n]]
            propres[f["name"]] = (listes[0], min([plafond, *bornes]), tuple(listes[1:]))
        if not propres:
            continue
        premier = next(iter(propres.values()))
        for f in ecrivent:
            out[f"{outil}:{f['name']}"] = propres.get(f["name"], premier)
    return out


def pas_un_lot(description: dict, plafond: int) -> dict[str, str]:
    """`tools/effets.PAS_UN_LOT` lines: the list arguments of a declared tool that no op carries as a batch (a read or
    a destruction that takes a list)."""
    declares = effets(description)
    lots_ = lots(description, plafond)
    out = {}
    for outil, fonctions in outils(description).items():
        if outil not in declares:
            continue
        listes = {n for f in fonctions for n in _listes(f)}
        portees = {c for k, (cle, _, avec) in lots_.items() if k.partition(":")[0] == outil for c in (cle, *avec)}
        reste = sorted(listes - portees)
        if reste:
            out[outil] = " ".join(reste)
    return out


# --- personal data -------------------------------------------------------------------------------------------------

def _personnels(schema, nom: Optional[str], out: set) -> None:
    """The argument names under which a `personal: true` value travels, at any depth (an element of a list, a branch,
    the free keys of an object: the name of the property that holds them)."""
    if isinstance(schema, list):
        for branche in schema:
            _personnels(branche, nom, out)
        return
    if not isinstance(schema, dict):
        return
    if schema.get("personal") is True and nom:
        out.add(nom)
    for cle, sous in (schema.get("properties") or {}).items():
        _personnels(sous, cle, out)
    for mot in ("items", "additionalProperties", "anyOf", "oneOf", "allOf", "prefixItems"):
        if mot in schema:
            _personnels(schema[mot], nom, out)


def noms_personnels(schema: dict) -> frozenset:
    """The argument names of an input under which a person travels."""
    out: set = set()
    _personnels(schema, None, out)
    return frozenset(out)


def personnels(description: dict) -> dict[str, frozenset]:
    """`{tool: argument names that carry a person}`, for the call log's masking (`journal_secrets`)."""
    out = {}
    for outil, fonctions in outils(description).items():
        noms = frozenset().union(*(noms_personnels(f["input"]) for f in fonctions))
        if noms:
            out[outil] = frozenset(noms)
    return out


# --- what the reader serves ----------------------------------------------------------------------------------------

def secret_unique(description: dict) -> dict:
    """The one secret field of the credential (a key, or a service account's JSON key file), `DescriptionNonServie`
    otherwise."""
    connecteur = description["connector"]
    champs = connecteur.get("credential") or []
    sorte = connecteur["auth"]["kind"]
    if ((sorte not in _AUTH_A_CLE and sorte != _AUTH_A_COMPTE_DE_SERVICE) or len(champs) != 1
            or champs[0].get("secret") is not True or champs[0].get("holder", "account") != "account"):
        raise DescriptionNonServie(f"{connecteur['name']}: the credential is not one secret of the account "
                                   f"(auth {connecteur['auth']['kind']}, {len(champs)} field(s))")
    return champs[0]


def identifiant_et_mot_de_passe(description: dict) -> bool:
    """The credential is a login and a password (`basic`), two fields, not one secret."""
    return description["connector"]["auth"]["kind"] == _AUTH_BASIQUE


def champs_du_compte(description: dict) -> tuple:
    """The credential fields the reader serves, in the order of the description: the one secret
    (`secret_unique`), or the login then the password that a `basic` auth names — the login not secret, the password
    secret, both of the account. `DescriptionNonServie` otherwise."""
    connecteur = description["connector"]
    if not identifiant_et_mot_de_passe(description):
        return (secret_unique(description),)
    champs = connecteur.get("credential") or []
    auth = connecteur["auth"]
    par_nom = {c["name"]: c for c in champs}
    login, mot_de_passe = par_nom.get(auth.get("username")), par_nom.get(auth.get("password"))
    if (len(champs) != 2 or login is None or mot_de_passe is None or login is mot_de_passe
            or login.get("secret") is True or mot_de_passe.get("secret") is not True
            or any(c.get("holder", "account") != "account" for c in champs)):
        raise DescriptionNonServie(f"{connecteur['name']}: the credential is not one secret of the account, nor its "
                                   f"login and password (auth basic, {len(champs)} field(s))")
    return tuple(c for c in champs if c is login or c is mot_de_passe)


def compte_de_service(description: dict) -> bool:
    """The one secret is a service account's JSON key file (`oauth2_jwt_bearer`), not a key."""
    return description["connector"]["auth"]["kind"] == _AUTH_A_COMPTE_DE_SERVICE


def champ_du_coffre(description: dict) -> str:
    """The name of the credential field in the vault: `key` for a key, the description's own for a service account
    (`providers._model._decrit`)."""
    return secret_unique(description)["name"] if compte_de_service(description) else CHAMP_DE_CLE


def _refus_du_moteur(description: dict, f: dict) -> Optional[str]:
    """What the engine would refuse of the function before sending anything (`Unsupported`), judged here at mount."""
    from oto.connectors.engine.errors import Unsupported
    from oto.connectors.engine.support import refuse_unsupported
    try:
        refuse_unsupported(description, f)
    except Unsupported as e:
        return str(e)
    return None


def _refus_de_la_fonction(description: dict, f: dict) -> list[str]:
    # `async` (a job whose cost its collect settles) has no place in oto 1 yet; `checks` and `expect` raise a refusal
    # without a status, which the error taxonomy does not classify yet. `scopes` (what an access level must grant) is
    # served since 13/11/2026: `niveaux_d_acces`.
    raisons = [f"function {f['name']}: {cle}" for cle in ("async", "checks", "expect") if cle in f]
    moteur = _refus_du_moteur(description, f)
    if moteur is not None:
        raisons.append(moteur)
    if f["class"] == "sensitive" and f.get("effect") not in _PAR_EFFET:
        raisons.append(f"function {f['name']}: sensitive without `effect` (send or destroy)")
    return raisons


def niveaux_d_acces(description: dict) -> Optional[dict]:
    """The access levels the description declares (`auth.access_levels`), in the form `connectors.access_levels`
    validates: `levels` and `scope_implies` as tuples, `tools` = `{tool: {op: the scopes the function requires}}` for
    the served pair, `default` = `auth.default_level` (else `full`), and `widening_needs_consent` false for a service
    account, whose next assertion claims the wider scopes without asking anyone. `None` without levels."""
    auth = description["connector"]["auth"]
    if "access_levels" not in auth:
        return None
    return {
        "levels": {nom: tuple(niveau["scopes"]) for nom, niveau in auth["access_levels"].items()},
        "scope_implies": {s: tuple(v) for s, v in (auth.get("scope_implies") or {}).items()},
        "tools": {outil: {f["name"]: tuple(f["scopes"]) for f in fonctions}
                  for outil, fonctions in outils(description).items()},
        "default": auth.get("default_level", "full"),
        "widening_needs_consent": not compte_de_service(description),
    }


def refus_de_montage(description: dict) -> list[str]:
    """Every reason why the reader cannot serve this description; `[]` when it can. What the engine runs (an address
    by `base_urls`, a refusal under a success status) is not refused here; what it does not run is, in its words."""
    connecteur = description["connector"]
    raisons = []
    try:
        champs_du_compte(description)
    except DescriptionNonServie as e:
        raisons.append(str(e).split(": ", 1)[1])
    if "settings" in connecteur:
        # The engine resolves them, but oto 1 keeps no setting of a described account to give it.
        raisons.append("connector.settings")
    for f in description["functions"]:
        raisons += _refus_de_la_fonction(description, f)
        if any(a in f["input"]["properties"] and "pagination" not in f for a in ARGUMENTS_DE_PAGINATION):
            raisons.append(f"function {f['name']}: declares a pagination argument")
    return raisons


def verifier(description: dict) -> None:
    """`DescriptionNonServie` naming every reason, when the reader cannot serve the description."""
    raisons = refus_de_montage(description)
    if raisons:
        raise DescriptionNonServie(f"{description['connector']['name']}: not served by the reader: "
                                   + "; ".join(raisons))


# --- the index of the inscribed connectors ------------------------------------------------------------------------

@lru_cache(maxsize=1)
def classes_des_outils() -> dict[str, dict[str, str]]:
    """`{tool: {op: class}}` of every tool the reader serves (both sides, `LECTURE` included)."""
    out = {}
    for c in inscrits():
        for outil, fonctions in outils(charger(c.name)).items():
            out[outil] = {f["name"]: classe(f) for f in fonctions}
    return out


def classe_d_un_appel(outil: str, op: Optional[str]) -> Optional[str]:
    """The class of a call of a served tool, `None` when the tool is not served by the reader. An op it does not
    serve raises, naming those it does: never presumed to read."""
    par_op = classes_des_outils().get(outil)
    if par_op is None:
        return None
    if op not in par_op:
        raise ValueError(f"`{outil}` serves no op {op!r} (ops: {', '.join(par_op)})")
    return par_op[op]


@lru_cache(maxsize=1)
def personnels_des_outils() -> dict[str, frozenset]:
    """`{tool: personal argument names}` of every tool the reader serves."""
    out: dict[str, frozenset] = {}
    for c in inscrits():
        out.update(personnels(charger(c.name)))
    return out
