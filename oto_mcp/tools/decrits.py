"""The GENERIC READER: serves a described connector from its description, written once for all (05/11/2026).

A connector inscribed by `providers._model._decrit` has no `tools/<name>.py`: this module mounts its PAIR from the
description the library carries (`oto.connectors.descriptions`, generated by the fabrique) and runs each call by the
library's ENGINE (`oto.connectors.engine`, 09/11/2026): the request, its authentication, the error table, the shaping
of the answer and the pages are the description's, as oto-core's engine runs them for oto 2. No client is written per
connector. What the description derives (pair, effects, batches, personal arguments, mount refusals) is
`connectors/descriptions.py`.

- `<ns>` serves the functions `act: false` (`LECTURE`, `SIMULATION` with a draft), `<ns>_act` the functions `act: true`
  (`ACTE`). A call names its function in `op` and passes that function's arguments; the tool's schema is the union of
  its functions' schemas, and each call is validated (JSON Schema 2020-12) against its function's own schema. A call
  refused there answers the function's description, schema and example.
- The credential is the caller's, resolved at each call: a key by `access.resolve_api_key`, a service account's JSON
  key file by `access.resolve_credential_fields`, a login and a password (`basic`) by `access.resolve_credential`.
  It is given to the engine under the description's field names; the engine reads no secret anywhere else.
- A connector with mode `platform` resolves the shared key as any shared key resolves (closed or open, grants, quota:
  the registry entry and the cascade decide, never this module). The probe function reads the account itself: on the
  shared key it is the platform's account, refused.
- Every successful call notes on its trace the `quantity` its declared cost settles (`oto.connectors.cost`: read in
  the answer when the cost says `settle`, the requests otherwise), 0 for a function without cost: the partner billing
  axis (`tool_calls.quantity`), on any key, never left NULL (the ledger reads NULL as 1). A refused call notes
  nothing. Quota `units` are never noted: a platform connector served here is in `access.reglement.SANS_DEBIT`.
- A refusal the description names (`engine.Refused`) becomes `RefusNomme` (`status_code`, `retryable`,
  `credential_rejected` from `marks_account`), which the error taxonomy reads like any upstream error; an undeclared
  status passes as the engine raised it (`UpstreamHTTPError`, its body masked of the call's secrets).
- A connector whose description declares access levels (`auth.access_levels`) is governed like any leveled
  connector (`connectors/access_levels.py`): the org's or team's level, else the description's `default_level`. The
  guard (`connectors/access_level_gate.py`) refuses what the level does not cover before the tool runs; the engine
  receives the level of the call (`access_level=`), refuses on its own what it does not serve, and a service account
  claims that level's scopes. Both refusals, and a level the description no longer declares, say the gesture: an org
  admin sets the level (`oto_connector_access_level`).
- The probe (`connector.probe`) is registered with `connectors/verify`, `auth`, or `auth+quota` with a balance.
- What it does not know how to serve is refused at MOUNT (`descriptions.verifier`), never approximated at call time.
"""
