#: The key field of a served connector's credential in the vault (`providers._model._decrit`).
CHAMP_DE_CLE = "key"


class RefusNomme(Exception):
    """A refusal of the vendor named by the description: its fixed message (never the vendor's body), and what the
    error taxonomy reads — `status_code`, `retryable`, `credential_rejected` (a refusal that marks the key)."""

    def __init__(self, code: str, message: str, status_code: int, retryable: bool, marks_account: Optional[str]):
        self.code = code
        self.status_code = status_code
        self.retryable = retryable
        self.credential_rejected = marks_account == "credential_rejected"
        self.marks_account = marks_account
        super().__init__(f"{message} ({code})")


def _invalide(message: str) -> McpError:
    return McpError(ErrorData(code=INVALID_PARAMS, message=message))


def importer(chemin: str) -> type:
    """The client class named `"module:Class"`."""
    module, _, classe = chemin.partition(":")
    if not module or not classe:
        raise descriptions.DescriptionNonServie(f"client {chemin!r}: expected 'module:Class'")
    return getattr(importlib.import_module(module), classe)


def verifier_client(description: dict, client: type) -> None:
    """The client follows its description: its constructor takes the credential field by name, and each function is a
    method of the same name that takes every argument of the function (pagination's aside; a `**keywords` parameter
    takes those it does not name, as a filter set), a parameter without default being a required argument. A parameter
    the description does not serve has a default: the reader never sends it (a secret the consumer's own code sets,
    for one). `DescriptionNonServie` naming every gap."""
    nom = description["connector"]["name"]
    champ = descriptions.secret_unique(description)["name"]
    ecarts = []
    if champ not in inspect.signature(client).parameters:
        ecarts.append(f"the constructor takes no {champ!r}")
    for f in description["functions"]:
        methode = getattr(client, f["name"], None)
        if not callable(methode):
            ecarts.append(f"no method {f['name']}")
            continue
        tous = list(inspect.signature(methode).parameters.values())[1:]
        libres = any(p.kind is inspect.Parameter.VAR_KEYWORD for p in tous)
        parametres = {p.name: p for p in tous if p.kind not in (inspect.Parameter.VAR_KEYWORD,
                                                                 inspect.Parameter.VAR_POSITIONAL)}
        arguments = set(f["input"]["properties"]) - set(descriptions.ARGUMENTS_DE_PAGINATION)
        refuses = set() if libres else arguments - set(parametres)
        if refuses:
            ecarts.append(f"{f['name']}: takes no {sorted(refuses)}")
        requis = set(f["input"].get("required", []))
        sans_defaut = {n for n, p in parametres.items() if p.default is inspect.Parameter.empty}
        if not sans_defaut <= requis:
            ecarts.append(f"{f['name']}: {sorted(sans_defaut - requis)} required by the client, optional in its input")
    if ecarts:
        raise descriptions.DescriptionNonServie(f"{nom}: the client {client.__name__} does not follow its description: "
                                                + "; ".join(ecarts))


# --- the schema and the text of a tool ---------------------------------------------------------------------------

def schema_union(fonctions: list[dict]) -> dict:
    """The tool's input: `op` (the function names) and the union of the functions' arguments; an argument two
    functions declare differently is either of them (`anyOf`). Each call is validated against its function's own."""
    proprietes: dict[str, Any] = {}
    for f in fonctions:
        for nom, schema in f["input"]["properties"].items():
            deja = proprietes.get(nom)
            if deja is None:
                proprietes[nom] = schema
            elif deja != schema:
                branches = deja["anyOf"] if set(deja) == {"anyOf"} else [deja]
                if schema not in branches:
                    proprietes[nom] = {"anyOf": [*branches, schema]}
    op = {"type": "string", "enum": [f["name"] for f in fonctions],
          "description": "The function to call; the other arguments are that function's."}
    return {"type": "object", "additionalProperties": False, "required": ["op"],
            "properties": {"op": op, **proprietes}}


def _phrase(texte: str) -> str:
    texte = " ".join(texte.split())
    fin = texte.find(". ")
    return texte if fin < 0 else texte[:fin + 1]


def texte_de_l_outil(description: dict, outil: str, fonctions: list[dict]) -> str:
    """The tool's description: what the side does, then one sentence per op."""
    label = description["connector"]["label"]
    ns = descriptions.espace(description)
    if outil == ns:
        tete = (f"{label} — read{' or prepare' if descriptions.lecteur_simule(fonctions) else ''}. Nothing is sent "
                f"or destroyed here{f' (that is `{ns}_act`)' if len(descriptions.outils(description)) > 1 else ''}.")
    else:
        tete = f"{label} — act: what this tool does reaches the vendor, sends or destroys. Reading is `{ns}`."
    ops = "\n".join(f"- `{f['name']}` — {_phrase(f['description'])}" for f in fonctions)
    return (f"{tete}\n\nPass `op` and that op's arguments only. A call that does not match its op's schema answers "
            f"the op's full description, schema and an example.\n\nOps:\n{ops}")


def _refus_de_forme(outil: str, f: dict, erreur) -> str:
    """The refusal of a malformed call: what is wrong and where, then the op's description, schema and example."""
    chemin = "/".join(str(p) for p in erreur.absolute_path) or "(root)"
    exemple = f["examples"][0]["input"]
    return (
        f"{outil} op `{f['name']}`: {erreur.message} (at {chemin}). Nothing was done.\n{f['description'].strip()}\n"
        f"Input schema: {json.dumps(f['input'], ensure_ascii=False)}\n"
        f"Example: {json.dumps({'op': f['name'], **exemple}, ensure_ascii=False)}")


# --- serving one connector ---------------------------------------------------------------------------------------

class Servi:
    """One served connector: its description, its client, and the calls of its functions."""

    def __init__(self, nom: str, description: dict, client: type):
        self.nom = nom
        self.description = description
        self.client = client
        self.champ = descriptions.secret_unique(description)["name"]
        self.fonctions = {f["name"]: f for f in description["functions"]}
        self.validateurs = {n: Draft202012Validator(f["input"]) for n, f in self.fonctions.items()}

    def instance(self, cle: str):
        """The connector's client holding `cle`. Not a `_client()` factory of one known class: the class is the
        inscribed one, its methods are the description's functions, checked once at mount (`verifier_client`)."""
        return self.client(**{self.champ: cle})

    def valider(self, outil: str, ops: list[str], arguments: dict) -> tuple[dict, dict]:
        """`(function, its arguments)` of a call of `outil`, refused (`INVALID_PARAMS`) when its op is not one of the
        tool's or its arguments do not match the op's schema."""
        args = dict(arguments)
        op = args.pop("op", None)
        if op not in ops:
            raise _invalide(f"`{outil}`: `op` must be one of {', '.join(ops)} (got {op!r}). Nothing was done.")
        erreur = next(iter(sorted(self.validateurs[op].iter_errors(args), key=lambda e: list(e.absolute_path))), None)
        if erreur is not None:
            raise _invalide(_refus_de_forme(outil, self.fonctions[op], erreur))
        return self.fonctions[op], args

    def _refus(self, f: dict, erreur) -> Optional[RefusNomme]:
        """The named refusal of the vendor's HTTP error, `None` when the description names none for its status."""
        entree = serve.refusal(self.description, f, erreur.status_code, erreur.body)
        if entree is None:
            return None
        return RefusNomme(entree["code"], entree["message"], erreur.status_code, entree["retryable"],
                          entree["marks_account"])

    def appeler(self, f: dict, args: dict) -> dict:
        """Call the function with the caller's key: each page read, the vendor's refusal named, the answer shaped."""
        from oto.tools.common.errors import UpstreamHTTPError

        cle, _ = access.resolve_api_key(self.nom)
        methode = getattr(self.instance(cle), f["name"])
        reponses: list = []
        curseur = None
        for _ in range(serve.page_count(f, args)):
            try:
                reponse = methode(**serve.call_arguments(f, args, curseur))
            except UpstreamHTTPError as e:
                refus = self._refus(f, e)
                if refus is None:
                    raise
                raise refus from e
            except ValueError as e:
                message = str(e)
                for valeur in _masques(f, args):
                    message = message.replace(valeur, "[personal]")
                raise _invalide(f"{message} Nothing was done.") from None
            reponses.append(reponse)
            curseur = serve.next_cursor(f, reponse)
            if curseur is None:
                break
        return serve.result(f, reponses, curseur)

    def sonder(self, fields: dict, config: Optional[dict] = None) -> Optional[dict]:  # noqa: ARG002
        """"Test connection": the description's probe function, no argument; a named refusal that marks the key is
        `NonAutorise`, one that marks the credits `QuotaEpuise`; an unhealthy answer raises with its reason."""
        from oto.tools.common.errors import UpstreamHTTPError

        sonde = self.description["connector"]["probe"]
        f = self.fonctions[sonde["function"]]
        try:
            reponse = getattr(self.instance(fields.get(CHAMP_DE_CLE)), f["name"])()
        except UpstreamHTTPError as e:
            refus = self._refus(f, e)
            if refus is None:
                raise
            if refus.marks_account == "credential_rejected":
                raise connector_verify.NonAutorise(str(refus)) from e
            if refus.marks_account == "quota_exhausted":
                raise connector_verify.QuotaEpuise(str(refus)) from e
            raise refus from e
        sante = serve.probe_health(self.description, reponse)
        solde = sante.get("balance")
        if not sante["healthy"]:
            if solde is not None and solde["value"] is not None and solde["value"] < solde["min"]:
                raise connector_verify.QuotaEpuise(sante["reason"])
            raise RuntimeError(sante["reason"])
        if solde is None:
            return None
        return {"quota": {"restant": solde["value"], "unite": solde["unit"], "seuil": solde["min"]}}


def _masques(f: dict, args: dict) -> list[str]:
    """The texts of the personal arguments of a call, longest first: replaced in a message the client raises."""
    noms = descriptions.noms_personnels(f["input"])
    textes: set = set()

    def tout(v):
        if isinstance(v, bool) or v is None:
            return
        if isinstance(v, (str, int, float)):
            if str(v):
                textes.add(str(v))
        elif isinstance(v, (list, tuple)):
            for e in v:
                tout(e)
        elif isinstance(v, dict):
            for e in v.values():
                tout(e)

    def chercher(v):
        if isinstance(v, dict):
            for k, e in v.items():
                tout(e) if k in noms else chercher(e)
        elif isinstance(v, list):
            for e in v:
                chercher(e)

    chercher(args)
    return sorted(textes, key=len, reverse=True)


class OutilDecrit(Tool):
    """One tool of a served pair: its schema is the union of its functions', each call goes to `Servi`."""

    _servi: Servi = PrivateAttr()
    _ops: list = PrivateAttr()

    @classmethod
    def monte(cls, servi: Servi, outil: str, fonctions: list[dict]) -> "OutilDecrit":
        ns = descriptions.espace(servi.description)
        annotations = (ACTE if outil != ns else SIMULATION if descriptions.lecteur_simule(fonctions) else LECTURE)
        tool = cls(name=outil, description=texte_de_l_outil(servi.description, outil, fonctions),
                   parameters=schema_union(fonctions), annotations=annotations)
        tool._servi = servi
        tool._ops = [f["name"] for f in fonctions]
        return tool

    @property
    def servi(self) -> Servi:
        return self._servi

    async def run(self, arguments: dict[str, Any]) -> ToolResult:
        f, args = self._servi.valider(self.name, self._ops, arguments)
        return self.convert_result(await asyncio.to_thread(self._servi.appeler, f, args))


def monter(mcp: FastMCP, nom: str, description: dict, client: type) -> tuple[OutilDecrit, ...]:
    """Mount the pair of one described connector and register its probe; refuse, before mounting anything, a
    description the reader cannot serve or a client that does not follow it."""
    descriptions.verifier(description)
    verifier_client(description, client)
    servi = Servi(nom, description, client)
    montes = tuple(OutilDecrit.monte(servi, outil, fonctions)
                   for outil, fonctions in descriptions.outils(description).items())
    for outil in montes:
        mcp.add_tool(outil)
    sonde = description["connector"].get("probe")
    if sonde is not None:
        couvre = connector_verify.AUTH_QUOTA if "balance" in sonde else connector_verify.AUTH
        connector_verify.register(nom, servi.sonder, couvre=couvre)
    return montes


def register(mcp: FastMCP) -> None:
    """Mount every inscribed connector (`providers._model._decrit`)."""
    for c in descriptions.inscrits():
        monter(mcp, c.name, descriptions.charger(c.name), importer(c.client))
