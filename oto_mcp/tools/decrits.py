logger = logging.getLogger(__name__)


class RefusNomme(Exception):
    """A refusal named by the description (`engine.Refused`): its fixed message (never the vendor's body), and what
    the error taxonomy reads — `status_code` (`None` for a refusal of the key before anything is sent), `retryable`,
    `credential_rejected` (a refusal that marks the key)."""

    def __init__(self, refus: engine.Refused):
        self.code = refus.code
        self.status_code = refus.status_code
        self.retryable = refus.retryable
        self.credential_rejected = refus.credential_rejected
        self.marks_account = refus.marks_account
        super().__init__(str(refus))


def _invalide(message: str) -> McpError:
    return McpError(ErrorData(code=INVALID_PARAMS, message=message))


# --- the schema and the text of a tool ---------------------------------------------------------------------------

def schema_union(fonctions: list[dict]) -> dict:
    """The tool's input: `op` (the function names) and the union of the functions' arguments; an argument two
    functions declare differently is either of them (`anyOf`). Each call is validated against its function's own."""
    proprietes: dict[str, Any] = {}
    for f in fonctions:
        for nom, schema in f["input"]["properties"].items():
            deja = proprietes.get(nom)
            if deja is None:
                proprietes[nom] = schema
            elif deja != schema:
                branches = deja["anyOf"] if set(deja) == {"anyOf"} else [deja]
                if schema not in branches:
                    proprietes[nom] = {"anyOf": [*branches, schema]}
    op = {"type": "string", "enum": [f["name"] for f in fonctions],
          "description": "The function to call; the other arguments are that function's."}
    return {"type": "object", "additionalProperties": False, "required": ["op"],
            "properties": {"op": op, **proprietes}}


def _phrase(texte: str) -> str:
    texte = " ".join(texte.split())
    fin = texte.find(". ")
    return texte if fin < 0 else texte[:fin + 1]


def texte_de_l_outil(description: dict, outil: str, fonctions: list[dict]) -> str:
    """The tool's description: what the side does, then one sentence per op."""
    label = description["connector"]["label"]
    ns = descriptions.espace(description)
    if outil == ns:
        tete = (f"{label} — read{' or prepare' if descriptions.lecteur_simule(fonctions) else ''}. Nothing is sent "
                f"or destroyed here{f' (that is `{ns}_act`)' if len(descriptions.outils(description)) > 1 else ''}.")
    else:
        tete = f"{label} — act: what this tool does reaches the vendor, sends or destroys. Reading is `{ns}`."
    ops = "\n".join(f"- `{f['name']}` — {_phrase(f['description'])}" for f in fonctions)
    return (f"{tete}\n\nPass `op` and that op's arguments only. A call that does not match its op's schema answers "
            f"the op's full description, schema and an example.\n\nOps:\n{ops}")


def _refus_de_forme(outil: str, f: dict, erreur) -> str:
    """The refusal of a malformed call: what is wrong and where, then the op's description, schema and example."""
    chemin = "/".join(str(p) for p in erreur.absolute_path) or "(root)"
    exemple = f["examples"][0]["input"]
    return (
        f"{outil} op `{f['name']}`: {erreur.message} (at {chemin}). Nothing was done.\n{f['description'].strip()}\n"
        f"Input schema: {json.dumps(f['input'], ensure_ascii=False)}\n"
        f"Example: {json.dumps({'op': f['name'], **exemple}, ensure_ascii=False)}")


# --- serving one connector ---------------------------------------------------------------------------------------

class Servi:
    """One served connector: its description, the vault field of its credential, and the calls of its functions."""

    def __init__(self, nom: str, description: dict):
        self.nom = nom
        self.description = description
        self.champs = tuple(c["name"] for c in descriptions.champs_du_compte(description))
        self.basique = descriptions.identifiant_et_mot_de_passe(description)
        self.champ = self.champs[0]
        self.coffre = None if self.basique else descriptions.champ_du_coffre(description)
        self.plateforme = "platform" in description["connector"]["modes"]
        self.sonde = (description["connector"].get("probe") or {}).get("function")
        self.fonctions = {f["name"]: f for f in description["functions"]}
        self.a_niveaux = "access_levels" in description["connector"]["auth"]
        self.validateurs = {n: Draft202012Validator(f["input"]) for n, f in self.fonctions.items()}

    def _credential_de_l_appelant(self) -> tuple[dict, bool]:
        """`(credential for the engine, on the platform key)`, resolved as the vault keeps it: a key, a service
        account's JSON key file, or a login and a password (both fields, under the description's names)."""
        if descriptions.compte_de_service(self.description):
            return {self.champ: access.resolve_credential_fields(self.nom)[self.coffre]}, False
        if self.basique:
            rc = access.resolve_credential(self.nom, want="auto" if self.plateforme else "byo")
            champs = rc.fields
            manquent = [c for c in self.champs if not champs.get(c)]
            if manquent:
                raise _invalide(f"The {self.description['connector']['label']} credential lacks "
                                f"{', '.join(manquent)}: set it again on the connector. Nothing was done.")
            return {c: champs[c] for c in self.champs}, rc.is_platform
        cle, sur_plateforme = access.resolve_api_key(self.nom)
        return {self.champ: cle}, sur_plateforme

    def _noter_la_quantite(self, f: dict, args: dict, answers: list) -> None:
        """The call's settled quantity on its trace (`cost.settled_quantity`), 0 without a declared cost; a quantity
        read above the worst case is noted as read, and logged."""
        regle = cost.settled_quantity(self.description["connector"]["name"], f["name"], args, answers)
        if regle is not None and regle["exceeded"]:
            logger.warning("%s.%s: settled %s %s, above its declared worst case", self.nom, f["name"],
                           regle["quantity"], regle["unit"])
        session_org.note_call_trace(quantity=0 if regle is None else int(regle["quantity"]))

    def valider(self, outil: str, ops: list[str], arguments: dict) -> tuple[dict, dict]:
        """`(function, its arguments)` of a call of `outil`, refused (`INVALID_PARAMS`) when its op is not one of the
        tool's or its arguments do not match the op's schema."""
        args = dict(arguments)
        op = args.pop("op", None)
        if op not in ops:
            raise _invalide(f"`{outil}`: `op` must be one of {', '.join(ops)} (got {op!r}). Nothing was done.")
        erreur = next(iter(sorted(self.validateurs[op].iter_errors(args), key=lambda e: list(e.absolute_path))), None)
        if erreur is not None:
            raise _invalide(_refus_de_forme(outil, self.fonctions[op], erreur))
        return self.fonctions[op], args

    def appeler(self, f: dict, args: dict) -> dict:
        """Call the function by the engine with the caller's credential: every page read, the refusal named, the
        quantity noted, the answer shaped (`serve.result`)."""
        credential, sur_plateforme = self._credential_de_l_appelant()
        if sur_plateforme and f["name"] == self.sonde:
            raise _invalide(f"op `{f['name']}` reads the {self.description['connector']['label']} account itself; "
                            "this call runs on the shared platform key, whose account is the platform's. "
                            "Nothing was done.")
        niveau = access_level_gate.level_of_the_call(self.nom) if self.a_niveaux else None
        try:
            pages = engine.execute(self.description, f["name"], args, credential=credential, access_level=niveau)
        except engine.UnknownAccessLevel as e:
            raise RefusNomme(engine.Refused("unknown_access_level", f"{e} {self._geste_du_niveau()}")) from e
        except engine.Refused as refus:
            if refus.code == "access_level_denied":
                texte = str(refus).removesuffix(f" ({refus.code})")
                refus = engine.Refused(refus.code, f"{texte} {self._geste_du_niveau('full')}")
            raise RefusNomme(refus) from refus
        except engine.InvalidArguments as e:
            message = str(e)
            for valeur in _masques(f, args):
                message = message.replace(valeur, "[personal]")
            raise _invalide(f"{message} Nothing was done.") from None
        self._noter_la_quantite(f, args, pages.answers)
        return serve.result(serve.function(self.description, f["name"]), pages.answers, pages.next_cursor)

    def _geste_du_niveau(self, niveau: Optional[str] = None) -> str:
        """What sets the level right: an org admin, by `oto_connector_access_level`."""
        niveaux = ", ".join(self.description["connector"]["auth"]["access_levels"])
        return (f"Nothing was sent. An org admin sets the level of the organization "
                f"({'`' + niveau + '`' if niveau else 'one of ' + niveaux}): oto_connector_access_level(op='set', "
                f"scope='org', org_id=<the organization's id, from oto_context>, name='{self.nom}', "
                f"level='{niveau or '<one of ' + niveaux + '>'}').")

    def sonder(self, fields: dict, config: Optional[dict] = None) -> Optional[dict]:  # noqa: ARG002
        """"Test connection": the description's probe function, no argument, by the engine; a refusal that marks the
        key is `NonAutorise`, one that marks the credits `QuotaEpuise`; an unhealthy answer raises with its reason."""
        sonde = self.description["connector"]["probe"]
        credential = ({c: fields.get(c) for c in self.champs} if self.basique
                      else {self.champ: fields.get(self.coffre)})
        try:
            pages = engine.execute(self.description, sonde["function"], {}, credential=credential)
        except (engine.Refused, engine.TokenRefused) as refus:
            if refus.marks_account == "credential_rejected":
                raise connector_verify.NonAutorise(str(refus)) from None
            if refus.marks_account == "quota_exhausted":
                raise connector_verify.QuotaEpuise(str(refus)) from None
            raise
        sante = serve.probe_health(self.description, pages.answers[0])
        solde = sante.get("balance")
        if not sante["healthy"]:
            if solde is not None and solde["value"] is not None and solde["value"] < solde["min"]:
                raise connector_verify.QuotaEpuise(sante["reason"])
            raise RuntimeError(sante["reason"])
        if solde is None:
            return None
        return {"quota": {"restant": solde["value"], "unite": solde["unit"], "seuil": solde["min"]}}


def _masques(f: dict, args: dict) -> list[str]:
    """The texts of the personal arguments of a call, longest first: replaced in a message the engine raises."""
    noms = descriptions.noms_personnels(f["input"])
    textes: set = set()

    def tout(v):
        if isinstance(v, bool) or v is None:
            return
        if isinstance(v, (str, int, float)):
            if str(v):
                textes.add(str(v))
        elif isinstance(v, (list, tuple)):
            for e in v:
                tout(e)
        elif isinstance(v, dict):
            for e in v.values():
                tout(e)

    def chercher(v):
        if isinstance(v, dict):
            for k, e in v.items():
                tout(e) if k in noms else chercher(e)
        elif isinstance(v, list):
            for e in v:
                chercher(e)

    chercher(args)
    return sorted(textes, key=len, reverse=True)


class OutilDecrit(Tool):
    """One tool of a served pair: its schema is the union of its functions', each call goes to `Servi`."""

    _servi: Servi = PrivateAttr()
    _ops: list = PrivateAttr()

    @classmethod
    def monte(cls, servi: Servi, outil: str, fonctions: list[dict]) -> "OutilDecrit":
        ns = descriptions.espace(servi.description)
        annotations = (ACTE if outil != ns else SIMULATION if descriptions.lecteur_simule(fonctions) else LECTURE)
        tool = cls(name=outil, description=texte_de_l_outil(servi.description, outil, fonctions),
                   parameters=schema_union(fonctions), annotations=annotations)
        tool._servi = servi
        tool._ops = [f["name"] for f in fonctions]
        return tool

    @property
    def servi(self) -> Servi:
        return self._servi

    @property
    def fonctions(self) -> list[dict]:
        """The described functions this tool serves, in the order of its `op` enum."""
        return [self._servi.fonctions[op] for op in self._ops]

    async def run(self, arguments: dict[str, Any]) -> ToolResult:
        f, args = self._servi.valider(self.name, self._ops, arguments)
        return self.convert_result(await asyncio.to_thread(self._servi.appeler, f, args))


def monter(mcp: FastMCP, nom: str, description: dict) -> tuple[OutilDecrit, ...]:
    """Mount the pair of one described connector and register its probe; refuse, before mounting anything, a
    description the reader cannot serve."""
    descriptions.verifier(description)
    servi = Servi(nom, description)
    montes = tuple(OutilDecrit.monte(servi, outil, fonctions)
                   for outil, fonctions in descriptions.outils(description).items())
    for outil in montes:
        mcp.add_tool(outil)
    sonde = description["connector"].get("probe")
    if sonde is not None:
        couvre = connector_verify.AUTH_QUOTA if "balance" in sonde else connector_verify.AUTH
        connector_verify.register(nom, servi.sonder, couvre=couvre)
    return montes


def register(mcp: FastMCP) -> None:
    """Mount every inscribed connector (`providers._model._decrit`)."""
    for c in descriptions.inscrits():
        monter(mcp, c.name, descriptions.charger(c.name))
