"""The GENERIC READER: serves a described connector from its description, written once for all (05/11/2026).

A connector inscribed by `providers._model._decrit` has no `tools/<name>.py`: this module mounts its PAIR from the
description the library carries (`oto.connectors.descriptions`, generated by the fabrique) and calls its library client,
method by method, through the pure functions of `oto.connectors.serve`. What the description derives (pair, effects,
batches, personal arguments, mount refusals) is `connectors/descriptions.py`.

- `<ns>` serves the functions `act: false` (`LECTURE`, `SIMULATION` with a draft), `<ns>_act` the functions `act: true`
  (`ACTE`). A call names its function in `op` and passes that function's arguments; the tool's schema is the union of
  its functions' schemas, and each call is validated (JSON Schema 2020-12) against its function's own schema. A call
  refused there answers the function's description, schema and example.
- The key is the caller's, resolved at each call (`access.resolve_api_key`), given to the client under the name of the
  description's credential field.
- An HTTP refusal of the vendor becomes the NAMED refusal of the description (`RefusNomme`: `status_code`,
  `retryable`, `credential_rejected` from `marks_account`), which the error taxonomy reads like any upstream error; an
  undeclared status passes as the client raised it.
- The answer is shaped by `output` (`items`, `strip`, `projection`); `all_pages` reads the following pages.
- The probe (`connector.probe`) is registered with `connectors/verify`, `auth`, or `auth+quota` with a balance.
- What it does not know how to serve is refused at MOUNT (`descriptions.verifier`), and so is a client that does not
  follow its description (`verifier_client`): never approximated at call time.
"""
